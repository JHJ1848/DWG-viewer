const key = 'dwg-viewer.language';
let current: Language = window.electronAPI?.language ?? (localStorage.getItem(key) === 'en' ? 'en' : 'zh');
const listeners = new Set<() => void>();
document.documentElement.lang = current === 'zh' ? 'zh-CN' : 'en';
function update(value: Language) {
  current = value;
  document.documentElement.lang = value === 'zh' ? 'zh-CN' : 'en';
  listeners.forEach(notify => notify());
}
window.electronAPI?.onLanguage?.(update);
function subscribe(notify: () => void) {
  listeners.add(notify);
  return () => { listeners.delete(notify); };
}
export function setLanguage(value: Language) {
  if (window.electronAPI?.setLanguage) void window.electronAPI.setLanguage(value);
  else { localStorage.setItem(key, value); update(value); }
}
export function useLanguage() {
  const language = useSyncExternalStore(subscribe, () => current);
  return { language, t: (text: string) => language === 'en' ? english[text] ?? text : text };
}

